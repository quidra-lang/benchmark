a <- unique(c(12,5,8,21,5,17,3,12,9))
b <- unique(c(8,14,21,6,14,3,25,6))
results <- list(union(a,b), intersect(a,b), setdiff(a,b), union(setdiff(a,b),setdiff(b,a)))
labels <- c("union", "intersection", "difference", "symmetric difference")
for (i in seq_along(labels)) cat(labels[i], ": ", paste(sort(results[[i]]), collapse = " "), "\n", sep = "")
